/**
 * Демо-макеты ORTA: типы и метаданные.
 *
 * Это витрина макетов из `docs/design/orta-screens.html`, перенесённая в код:
 * каждый экран — настоящий React-компонент, но данные в нём демонстрационные.
 * Отсюда два правила, которые держит весь раздел:
 *
 *  - на каждом экране стоит пометка «демо-данные», потому что показывать
 *    правдоподобные числа без пометки — это обман, а не макет;
 *  - статус экрана берётся из борда (`Работает`, `Ф2`, `В работе`, `План`) и
 *    означает ровно то же: где-то код есть, а где-то только проект.
 */

export type DemoStatus = 'Работает' | 'Ф2' | 'В работе' | 'План';

export interface DemoScreenMeta {
  /** Идентификатор и путь файла: `./screens/<id>.tsx`. */
  id: string;
  /** Мобильный экран (390×844) или консоль (1024×768). */
  kind: 'phone' | 'console';
  /** Номер и название раздела борда. */
  section: number;
  sectionTitle: string;
  title: string;
  status: DemoStatus;
  /** Что на экране, какие эндпоинты, что честно не сделано. */
  note: string;
  /** Где это живёт или будет жить в коде. */
  code: string;
  /** Эндпоинты и события: реальные или предлагаемые. */
  endpoints: string;
  /** Готовый экран приложения: ссылка вместо макета. */
  realRoute?: string;
}

export const STATUS_LABEL: Record<DemoStatus, string> = {
  'Работает': 'Работает',
  'Ф2': 'Ф2 — сделано',
  'В работе': 'В работе',
  'План': 'План',
};

export const STATUS_TONE: Record<DemoStatus, 'success' | 'info' | 'warning' | 'neutral'> = {
  'Работает': 'success',
  'Ф2': 'info',
  'В работе': 'warning',
  'План': 'neutral',
};

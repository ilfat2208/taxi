/** Ленивая загрузка компонента экрана: файл называется `./screens/<id>.tsx`. */
const modules = import.meta.glob<{ default: ComponentType }>('./screens/*.tsx');

export function loadScreen(id: string) {
  const loader = modules[`./screens/${id}.tsx`];
  if (!loader) throw new Error(`нет компонента экрана: ${id}`);
  return loader;
}

export const demoSections = [...new Set(demoMeta.map((m) => m.section))]
  .sort((a, b) => a - b)
  .map((section) => ({
    section,
    title: demoMeta.find((m) => m.section === section)!.sectionTitle,
    screens: demoMeta.filter((m) => m.section === section),
  }));

/** Есть ли уже перенесённый компонент: пока агенты пишут экраны, это важно. */
export function hasScreen(id: string) {
  return Boolean(modules['./screens/' + id + '.tsx']);
}

export function screenById(id: string) {
  return demoMeta.find((m) => m.id === id);
}

/**
 * Роли демо-режима: кто входит и что видит.
 *
 * Смысл раздела — пройти продукт так, как его пройдёт человек: выбрать роль на входе
 * и оказаться в своей рабочей области с меню, а не листать рамки макетов. Поэтому
 * роль описывает три вещи: каким экранам она соответствует, как выглядит её оболочка
 * (консоль на весь экран или мобильное приложение) и что честно сказать о данных.
 *
 * Роли не выдуманы: это те же роли, что в JWT приложения — CUSTOMER, MERCHANT,
 * DISPATCHER, SUPPORT, ADMIN — плюс водитель и курьер, которые в коде опираются на
 * driver-service и dispatch-service.
 */
import { demoMeta } from './registry';
import type { DemoScreenMeta } from './types';

export interface DemoRole {
  id: string;
  title: string;
  /** Кто это в жизни продукта. */
  who: string;
  /** Что человек увидит в этой роли. */
  what: string;
  /** Консоль на весь экран или мобильное приложение в узкой колонке. */
  shell: 'console' | 'mobile';
  /** Заголовок оболочки (шапка консоли). */
  shellTitle: string;
  /** Подпись роли в шапке. */
  roleBadge: string;
  /** Какие экраны показываем: по идентификаторам реестра. */
  screens: string[];
  /** Правда о том, что в этой роли работает по-настоящему, а что демонстрация. */
  honesty: string;
}

/** Экраны по префиксу идентификатора — так реестр и фрагменты связаны между собой. */
function byPrefix(...prefixes: string[]): string[] {
  return demoMeta.filter((s) => prefixes.some((p) => s.id.startsWith(p))).map((s) => s.id);
}

